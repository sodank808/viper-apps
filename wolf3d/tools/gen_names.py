#!/usr/bin/env python3
"""Writes main/engine/wolf_names.h: a #define for every global name the
engine defines, giving it the prefix wolf_.

The simulator links every ELF app into one program (sim/CMakeLists.txt), where
Wolf4SDL's globals (screen, player, Quit, viewwidth, ...) would meet other
apps' and the firmware's. wl_def.h includes this header first, so the engine's
files, and the app's files that name the engine's functions, use the prefixed
names. On a device it changes nothing but the names.

Run it after changing which globals the engine defines (it compiles the
engine with the host's C compiler and reads the names with nm):

    wolf3d/tools/gen_names.py
"""

import pathlib
import re
import subprocess
import sys
import tempfile

ENGINE = pathlib.Path(__file__).resolve().parent.parent / "main" / "engine"
HEADER = ENGINE / "wolf_names.h"
PREFIX = "wolf_"


def defined_globals(obj):
    out = subprocess.run(["nm", "-g", "-P", str(obj)], check=True, capture_output=True,
                         text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[1] in ("U", "u", "w", "v"):
            continue
        name = parts[0]
        if sys.platform == "darwin" and name.startswith("_"):
            name = name[1:]
        names.append(name)
    return names


def main():
    names = set()
    with tempfile.TemporaryDirectory() as tmp:
        for src in sorted(ENGINE.glob("*.c")):
            obj = pathlib.Path(tmp) / (src.stem + ".o")
            subprocess.run(["cc", "-c", "-std=gnu17", "-w", "-DWOLF_NAMES_GENERATING",
                            "-I", str(ENGINE), "-o", str(obj), str(src)], check=True)
            names.update(defined_globals(obj))
    # The platform's (wolf3d_*) are the app's names for the engine's calls to
    # it and are prefixed already; C++ names (dbopl) are in a namespace
    names = sorted(n for n in names
                   if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n)
                   and not n.startswith("wolf3d_") and not n.startswith("_Z"))
    lines = [
        "// Generated by wolf3d/tools/gen_names.py; don't edit. The engine's",
        "// global names, prefixed so they can't meet another app's in the",
        "// simulator, which links every app into one program.",
        "#ifndef WOLF_NAMES_H",
        "#define WOLF_NAMES_H",
        "#ifndef WOLF_NAMES_GENERATING",
    ]
    lines += [f"#define {n} {PREFIX}{n}" for n in names]
    lines += ["#endif", "#endif", ""]
    HEADER.write_text("\n".join(lines))
    print(f"{HEADER}: {len(names)} names")


if __name__ == "__main__":
    main()
