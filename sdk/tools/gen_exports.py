#!/usr/bin/env python3
"""Generate the loader's table of firmware symbols that ELF apps can call.

Reads the export lists in components/elf_loader/exports/ (one name per line,
optionally "name = firmware_symbol", and "if CONFIG_<option>"; see
exports/viper.txt) and writes a C file with g_viper_elfsyms[], sorted by name
so elf_find_sym() can binary-search it. With --sdkconfig (the build's
sdkconfig.json), a line with a CONFIG_ option is left out when the option is
off.
The build runs this (components/elf_loader/CMakeLists.txt); check_app_elf.py
reads the same lists, so the check and the firmware can't disagree.

    gen_exports.py --output esp_elf_exports.c --sdkconfig sdkconfig.json exports/*.txt
"""

import argparse
import json
import pathlib
import re
import sys

EXPORTS_DIR = pathlib.Path(__file__).resolve().parent.parent / "exports"

LINE_RE = re.compile(r"^([A-Za-z_]\w*)(?:\s*=\s*([A-Za-z_]\w*))?(?:\s+if\s+CONFIG_(\w+))?$")


def read_exports(paths=None, config=None):
    """Returns {name apps call: firmware symbol} from the export lists.

    config is the build's sdkconfig (sdkconfig.json's {option: value}, without
    the CONFIG_ prefix). Without it, every line counts, options or not: that's
    what an app may call on some firmware.
    """
    if paths is None:
        paths = sorted(EXPORTS_DIR.glob("*.txt"))
    exports = {}
    for path in paths:
        for number, line in enumerate(pathlib.Path(path).read_text().splitlines(), 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            m = LINE_RE.match(line)
            if not m:
                sys.exit(f"{path}:{number}: expected a name or 'name = firmware_symbol', got {line!r}")
            name, target, option = m.group(1), m.group(2) or m.group(1), m.group(3)
            if option and config is not None and not config.get(option):
                continue
            if name in exports:
                sys.exit(f"{path}:{number}: {name} is exported twice")
            exports[name] = target
    return exports


def generate(exports):
    lines = [
        "// GENERATED by components/elf_loader/tool/gen_exports.py from",
        "// components/elf_loader/exports/*.txt. Do not edit.",
        "",
        "#include <stddef.h>",
        "",
        '#include "private/elf_symbol.h"',
        "",
        "// Declared as char: only the addresses matter, and functions and data",
        "// both work that way. No headers, so nothing disagrees with the types.",
    ]
    lines.append('#pragma GCC diagnostic ignored "-Wbuiltin-declaration-mismatch"')
    for target in sorted(set(exports.values())):
        lines.append(f"extern char {target};")
    lines += ["", "// Sorted by name for elf_find_sym()'s binary search",
              "const struct esp_elfsym g_viper_elfsyms[] = {"]
    for name in sorted(exports):
        lines.append(f'    {{"{name}", &{exports[name]}}},')
    lines += ["};", "", f"const size_t g_viper_elfsyms_count = {len(exports)};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=pathlib.Path, required=True, help="C file to write")
    parser.add_argument("--sdkconfig", type=pathlib.Path,
                        help="the build's sdkconfig.json, for lines with a CONFIG_ option")
    parser.add_argument("lists", nargs="+", type=pathlib.Path, help="export lists")
    args = parser.parse_args()

    config = json.loads(args.sdkconfig.read_text()) if args.sdkconfig else None
    args.output.write_text(generate(read_exports(args.lists, config)))


if __name__ == "__main__":
    main()
