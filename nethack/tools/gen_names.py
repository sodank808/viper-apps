#!/usr/bin/env python3
"""Writes main/port/nh_names.h: a #define for every global name NetHack, Lua
and the port define, giving it the prefix nh_.

The simulator links every ELF app into one program (sim/CMakeLists.txt in the
firmware repo), where NetHack's globals (level, flags, panic, rnd, ...) and
Lua's (lua_newstate, ...; the firmware has a Lua of its own) would meet
others'. port/nh_sim.h includes this header in every NetHack, Lua and port
file when built for the simulator; a device build doesn't use it. The app's
C++ calls the port only through nh_port.h's nhv_* functions, which keep their
names.

Run it after changing which globals NetHack, Lua or the port define (it
compiles them with the host's C compiler and reads the names with nm):

    nethack/tools/gen_names.py
"""

import concurrent.futures
import os
import pathlib
import re
import subprocess
import sys
import tempfile

MAIN = pathlib.Path(__file__).resolve().parent.parent / "main"
HEADER = MAIN / "port" / "nh_names.h"
PREFIX = "nh_"
SOURCES = ["nethack/src", "nethack/sys/share", "lua", "port"]
INCLUDES = ["port", "nethack/include", "lua"]


def defined_globals(obj):
    out = subprocess.run(["nm", "-g", "-P", str(obj)], check=True, capture_output=True,
                         text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 2 or parts[1] in ("U", "u", "w", "v"):
            continue
        name = parts[0]
        if sys.platform == "darwin" and name.startswith("_"):
            name = name[1:]
        names.append(name)
    return names


def compile_one(src, tmp):
    obj = pathlib.Path(tmp) / (src.parent.name + "_" + src.stem + ".o")
    # NH_NAMES_GENERATING: leave out what only a device builds (nh_stubs.c, the
    # C library names it defines for a device)
    cmd = ["cc", "-c", "-std=gnu99", "-w", "-DNH_NAMES_GENERATING"]
    for inc in INCLUDES:
        cmd += ["-I", str(MAIN / inc)]
    subprocess.run(cmd + ["-o", str(obj), str(src)], check=True)
    return defined_globals(obj)


def main():
    sources = [src for folder in SOURCES for src in sorted((MAIN / folder).glob("*.c"))]
    names = set()
    with tempfile.TemporaryDirectory() as tmp:
        with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
            for found in pool.map(lambda s: compile_one(s, tmp), sources):
                names.update(found)
    # The port's calls into the app (nh_port.h, nh_sim.h) keep their names
    names = sorted(n for n in names
                   if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n) and not n.startswith("nhv_"))
    lines = [
        "/* Generated by nethack/tools/gen_names.py; don't edit. NetHack's, Lua's",
        "   and the port's global names, prefixed so they can't meet another",
        "   app's or the firmware's in the simulator, which links every app into",
        "   one program (port/nh_sim.h). */",
        "#ifndef NH_NAMES_H",
        "#define NH_NAMES_H",
    ]
    lines += [f"#define {n} {PREFIX}{n}" for n in names]
    lines += ["#endif", ""]
    HEADER.write_text("\n".join(lines))
    print(f"{HEADER}: {len(names)} names from {len(sources)} files")


if __name__ == "__main__":
    main()
